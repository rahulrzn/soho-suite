CREATE TABLE public.dataset_analytics_config (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id bigint NOT NULL REFERENCES public.business(id) ON DELETE CASCADE,
    dataset_id bigint NOT NULL REFERENCES public.dataset(id) ON DELETE CASCADE,
    date_column varchar(120) NOT NULL,
    line_amount_column varchar(120) NOT NULL,
    order_id_column varchar(120) NOT NULL,
    customer_id_column varchar(120),
    confirmed_currency varchar(3) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT dataset_analytics_business_uq UNIQUE (business_id),
    CONSTRAINT dataset_analytics_dataset_uq UNIQUE (dataset_id),
    CONSTRAINT dataset_analytics_column_names_check CHECK (
        btrim(date_column) <> ''
        AND btrim(line_amount_column) <> ''
        AND btrim(order_id_column) <> ''
        AND date_column <> line_amount_column
        AND date_column <> order_id_column
        AND line_amount_column <> order_id_column
        AND (customer_id_column IS NULL OR (
            btrim(customer_id_column) <> ''
            AND customer_id_column <> date_column
            AND customer_id_column <> line_amount_column
            AND customer_id_column <> order_id_column
        ))
    ),
    CONSTRAINT dataset_analytics_currency_check CHECK (confirmed_currency ~ '^[A-Z]{3}$')
);
