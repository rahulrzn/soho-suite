CREATE TABLE public.dataset (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id bigint NOT NULL REFERENCES public.business(id) ON DELETE CASCADE,
    created_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    name varchar(120) NOT NULL,
    description varchar(500),
    original_filename varchar(255) NOT NULL,
    file_type varchar(10) NOT NULL CHECK (file_type IN ('CSV', 'XLSX')),
    status varchar(20) NOT NULL CHECK (status IN ('PENDING_REVIEW', 'IMPORTED')),
    row_count integer NOT NULL DEFAULT 0 CHECK (row_count >= 0),
    column_count integer NOT NULL CHECK (column_count > 0 AND column_count <= 100),
    columns_json text NOT NULL,
    findings_json text NOT NULL,
    idempotency_key varchar(80) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    imported_at timestamptz,
    CONSTRAINT dataset_business_idempotency_key_uq UNIQUE (business_id, idempotency_key)
);
CREATE INDEX dataset_business_created_idx ON public.dataset (business_id, created_at DESC);

CREATE TABLE public.dataset_row (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id bigint NOT NULL REFERENCES public.dataset(id) ON DELETE CASCADE,
    row_number integer NOT NULL CHECK (row_number > 0),
    values_json text NOT NULL,
    CONSTRAINT dataset_row_dataset_number_uq UNIQUE (dataset_id, row_number)
);
CREATE INDEX dataset_row_dataset_number_idx ON public.dataset_row (dataset_id, row_number);
