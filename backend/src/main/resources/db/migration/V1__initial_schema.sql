-- Fresh-install representation of the confirmed legacy public schema.
-- Keep legacy columns and nullability intact; see backend/docs/database-migrations.md.

CREATE TABLE public.business (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    company varchar(255),
    country varchar(255),
    department varchar(255),
    business_email varchar(255),
    city varchar(255),
    pincode varchar(255),
    state varchar(255),
    CONSTRAINT business_pkey PRIMARY KEY (id)
);

CREATE TABLE public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    company varchar(255),
    country varchar(255),
    department varchar(255),
    phone_number bigint NOT NULL,
    email varchar(255) NOT NULL,
    first_name varchar(255) NOT NULL,
    last_name varchar(255) NOT NULL,
    password varchar(255) NOT NULL,
    phone varchar(255) NOT NULL,
    business_id bigint,
    firebase_uid varchar(255) NOT NULL,
    username varchar(30) NOT NULL,
    business_role varchar(20),
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT users_firebase_uid_key UNIQUE (firebase_uid),
    CONSTRAINT users_username_key UNIQUE (username),
    CONSTRAINT users_business_role_check
        CHECK (business_role IN ('OWNER', 'MANAGER', 'VIEWER')),
    CONSTRAINT users_business_id_fkey
        FOREIGN KEY (business_id) REFERENCES public.business (id)
);
