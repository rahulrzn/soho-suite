-- Expand the existing business model without replacing tables or changing primary keys.
CREATE SEQUENCE public.business_code_seq AS bigint START WITH 1 INCREMENT BY 1 NO CYCLE;

ALTER TABLE public.business
    ADD COLUMN business_code varchar(32),
    ADD COLUMN legal_business_name varchar(255),
    ADD COLUMN trading_name varchar(255),
    ADD COLUMN business_type varchar(40),
    ADD COLUMN industry varchar(255),
    ADD COLUMN legal_structure varchar(40),
    ADD COLUMN business_currency varchar(3) NOT NULL DEFAULT 'INR',
    ADD COLUMN financial_year_start_month smallint NOT NULL DEFAULT 4,
    ADD COLUMN business_status varchar(20) NOT NULL DEFAULT 'ACTIVE',
    ADD COLUMN created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP;

-- The legacy company value is explicitly the trading-name compatibility field.
UPDATE public.business
SET trading_name = company
WHERE trading_name IS NULL AND company IS NOT NULL;

-- Assign stable, unique codes using the sequence, never a row count.
DO $$
DECLARE
    business_row record;
BEGIN
    FOR business_row IN SELECT id FROM public.business ORDER BY id LOOP
        UPDATE public.business
        SET business_code = 'BIZ-' || lpad(nextval('public.business_code_seq')::text, 8, '0')
        WHERE id = business_row.id;
    END LOOP;
END;
$$;

ALTER TABLE public.business
    ALTER COLUMN business_code SET NOT NULL,
    ADD CONSTRAINT business_business_code_key UNIQUE (business_code),
    ADD CONSTRAINT business_business_type_check
        CHECK (business_type IS NULL OR business_type IN ('RETAIL', 'MANUFACTURING', 'SERVICES')),
    ADD CONSTRAINT business_legal_structure_check
        CHECK (legal_structure IS NULL OR legal_structure IN ('SOLE_PROPRIETORSHIP', 'PARTNERSHIP', 'PRIVATE_LIMITED')),
    ADD CONSTRAINT business_currency_format_check
        CHECK (business_currency ~ '^[A-Z]{3}$'),
    ADD CONSTRAINT business_financial_year_month_check
        CHECK (financial_year_start_month BETWEEN 1 AND 12),
    ADD CONSTRAINT business_status_check
        CHECK (business_status IN ('ACTIVE', 'SUSPENDED', 'CLOSED'));

CREATE TABLE public.business_location (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id bigint NOT NULL REFERENCES public.business(id) ON DELETE CASCADE,
    location_code varchar(40) NOT NULL,
    location_name varchar(120),
    location_type varchar(30) NOT NULL,
    address_line1 varchar(255),
    address_line2 varchar(255),
    city varchar(120),
    state varchar(120),
    postal_code varchar(40),
    country varchar(120),
    is_registered_address boolean NOT NULL DEFAULT false,
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT business_location_type_check
        CHECK (location_type IN ('REGISTERED_OFFICE', 'BRANCH', 'STORE', 'WAREHOUSE'))
);
CREATE UNIQUE INDEX business_location_business_code_uq
    ON public.business_location (business_id, lower(location_code));

-- Copy an existing legacy address only when at least one address value exists.
-- No missing address fields are fabricated; the legacy columns remain in place.
INSERT INTO public.business_location (
    business_id, location_code, location_name, location_type,
    city, state, postal_code, country, is_registered_address, is_active
)
SELECT id, 'LEGACY-' || id::text, 'Registered address', 'REGISTERED_OFFICE',
       city, state, pincode, country, true, true
FROM public.business
WHERE NULLIF(btrim(country), '') IS NOT NULL
   OR NULLIF(btrim(state), '') IS NOT NULL
   OR NULLIF(btrim(city), '') IS NOT NULL
   OR NULLIF(btrim(pincode), '') IS NOT NULL;

CREATE TABLE public.business_tax_registration (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id bigint NOT NULL REFERENCES public.business(id) ON DELETE CASCADE,
    registration_type varchar(40) NOT NULL,
    registration_number varchar(100) NOT NULL,
    jurisdiction varchar(120) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT business_tax_registration_status_check
        CHECK (status IN ('ACTIVE', 'PENDING', 'EXPIRED', 'INACTIVE'))
);
CREATE UNIQUE INDEX business_tax_registration_scope_uq
    ON public.business_tax_registration
       (business_id, lower(registration_type), lower(jurisdiction), lower(registration_number));

CREATE TABLE public.department (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id bigint NOT NULL REFERENCES public.business(id) ON DELETE CASCADE,
    department_code varchar(40) NOT NULL,
    department_name varchar(120) NOT NULL,
    is_active boolean NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX department_business_code_uq
    ON public.department (business_id, lower(department_code));
