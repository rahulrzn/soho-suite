-- Introduce canonical per-business memberships while retaining the legacy
-- users.business_id/business_role columns as a default-business compatibility view.
CREATE TABLE public.business_membership (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id bigint NOT NULL REFERENCES public.business(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    role varchar(20) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT business_membership_role_check CHECK (role IN ('OWNER', 'MANAGER', 'VIEWER')),
    CONSTRAINT business_membership_business_user_uq UNIQUE (business_id, user_id)
);

CREATE INDEX business_membership_user_idx ON public.business_membership (user_id);

DO $$
DECLARE
    source_count bigint;
    inserted_count bigint;
BEGIN
    IF EXISTS (
        SELECT 1
        FROM public.users u
        LEFT JOIN public.business b ON b.id = u.business_id
        WHERE (u.business_id IS NULL AND u.business_role IS NOT NULL)
           OR (u.business_id IS NOT NULL AND u.business_role IS NULL)
           OR (u.business_id IS NOT NULL AND u.business_role NOT IN ('OWNER', 'MANAGER', 'VIEWER'))
           OR (u.business_id IS NOT NULL AND b.id IS NULL)
    ) THEN
        RAISE EXCEPTION 'Cannot migrate business memberships: inconsistent legacy users.business_id/business_role assignments require reconciliation';
    END IF;

    SELECT count(*) INTO source_count
    FROM public.users
    WHERE business_id IS NOT NULL;

    INSERT INTO public.business_membership (business_id, user_id, role)
    SELECT business_id, id, business_role
    FROM public.users
    WHERE business_id IS NOT NULL;

    GET DIAGNOSTICS inserted_count = ROW_COUNT;
    IF inserted_count <> source_count THEN
        RAISE EXCEPTION 'Business membership backfill count mismatch: expected %, inserted %', source_count, inserted_count;
    END IF;
END;
$$;
