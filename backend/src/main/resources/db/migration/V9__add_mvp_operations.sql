CREATE TABLE public.business_activity (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id bigint NOT NULL,
    actor_user_id bigint,
    action varchar(80) NOT NULL,
    target_type varchar(40),
    target_id varchar(80),
    summary varchar(240) NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX business_activity_business_time_idx
    ON public.business_activity (business_id, occurred_at DESC, id DESC);

CREATE TABLE public.business_invitation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id bigint NOT NULL REFERENCES public.business(id) ON DELETE CASCADE,
    invited_email varchar(255) NOT NULL,
    invited_role varchar(20) NOT NULL CHECK (invited_role IN ('MANAGER', 'VIEWER')),
    token_hash char(64) NOT NULL UNIQUE,
    status varchar(20) NOT NULL CHECK (status IN ('PENDING', 'ACCEPTED', 'REVOKED', 'EXPIRED')),
    expires_at timestamptz NOT NULL,
    created_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX business_invitation_active_email_uq
    ON public.business_invitation (business_id, lower(invited_email)) WHERE status = 'PENDING';
CREATE INDEX business_invitation_business_status_idx ON public.business_invitation (business_id, status, expires_at);

CREATE TABLE public.business_ownership_transfer (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id bigint NOT NULL REFERENCES public.business(id) ON DELETE CASCADE,
    current_owner_user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    new_owner_user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    token_hash char(64) NOT NULL UNIQUE,
    status varchar(20) NOT NULL CHECK (status IN ('PENDING', 'ACCEPTED', 'REVOKED', 'EXPIRED')),
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (current_owner_user_id <> new_owner_user_id)
);
CREATE UNIQUE INDEX business_ownership_transfer_pending_uq
    ON public.business_ownership_transfer (business_id) WHERE status = 'PENDING';

CREATE TABLE public.business_expense (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id bigint NOT NULL REFERENCES public.business(id) ON DELETE CASCADE,
    created_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    expense_date date NOT NULL,
    amount numeric(19,4) NOT NULL CHECK (amount > 0),
    currency char(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    category varchar(32) NOT NULL CHECK (category IN ('RENT','UTILITIES','PAYROLL','MARKETING','SUPPLIES','TRANSPORT','PROFESSIONAL_SERVICES','MAINTENANCE','OTHER')),
    description varchar(240) NOT NULL,
    reference varchar(100),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX business_expense_business_date_idx ON public.business_expense (business_id, expense_date DESC, id DESC);
CREATE INDEX business_expense_business_category_date_idx ON public.business_expense (business_id, category, expense_date);

CREATE TABLE public.inventory_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id bigint NOT NULL REFERENCES public.business(id) ON DELETE CASCADE,
    name varchar(120) NOT NULL,
    sku varchar(80),
    description varchar(500),
    active boolean NOT NULL DEFAULT true,
    quantity numeric(19,4) NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    version bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX inventory_item_business_sku_uq ON public.inventory_item (business_id, lower(sku)) WHERE sku IS NOT NULL;
CREATE INDEX inventory_item_business_active_idx ON public.inventory_item (business_id, active, id);

CREATE TABLE public.inventory_movement (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id bigint NOT NULL REFERENCES public.business(id) ON DELETE CASCADE,
    item_id bigint NOT NULL REFERENCES public.inventory_item(id) ON DELETE CASCADE,
    actor_user_id bigint REFERENCES public.users(id) ON DELETE SET NULL,
    movement_type varchar(24) NOT NULL CHECK (movement_type IN ('OPENING_STOCK','RECEIPT','ADJUSTMENT','DAMAGE','COUNT_CORRECTION')),
    quantity_delta numeric(19,4) NOT NULL CHECK (quantity_delta <> 0),
    resulting_quantity numeric(19,4) NOT NULL CHECK (resulting_quantity >= 0),
    reason varchar(240) NOT NULL,
    idempotency_key varchar(80),
    request_fingerprint char(64),
    occurred_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (movement_type <> 'RECEIPT' OR quantity_delta > 0),
    CHECK (movement_type <> 'DAMAGE' OR quantity_delta < 0),
    CHECK (movement_type <> 'OPENING_STOCK' OR quantity_delta > 0)
);
CREATE UNIQUE INDEX inventory_movement_idempotency_uq
    ON public.inventory_movement (business_id, idempotency_key) WHERE idempotency_key IS NOT NULL;
CREATE INDEX inventory_movement_item_time_idx ON public.inventory_movement (business_id, item_id, occurred_at DESC, id DESC);
